#!/usr/bin/env python3
"""Regenerate the cross-harness projections of the t3-fleet dispatch skill.

The canonical sources are `skills/t3-fleet-dispatch/SKILL.md` and
`tools/t3-fleet-dispatch.md`. Everything under `.codex/`, `.claude/`,
`.cursor/`, and `.openclaw/` is derived from them, so a change to the skill
shows up as a reviewable diff in every harness surface instead of drifting
into untracked local state.

Usage:
    python3 scripts/project-skill.py          # write the projections
    python3 scripts/project-skill.py --check  # fail if any projection is stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKILL = ROOT / "skills" / "t3-fleet-dispatch" / "SKILL.md"
TOOL = ROOT / "tools" / "t3-fleet-dispatch.md"

BANNER = (
    "<!-- Generated by scripts/project-skill.py from "
    "skills/t3-fleet-dispatch/SKILL.md and tools/t3-fleet-dispatch.md. "
    "Edit those sources, then regenerate. -->"
)

DESCRIPTION = (
    "Route and supervise attached T3 child tasks, requested separate sessions, "
    "and app operations, and dispatch allowlisted fleet tasks across enrolled machines."
)

TARGETS = {
    ".codex/skills/t3-fleet/SKILL.md": (
        "---\n"
        "name: t3-fleet\n"
        f"description: {DESCRIPTION}\n"
        "---\n"
    ),
    ".claude/commands/t3-fleet.md": (
        "---\n"
        f"description: {DESCRIPTION}\n"
        "---\n"
    ),
    ".cursor/rules/t3-fleet.md": (
        "---\n"
        f"description: {DESCRIPTION}\n"
        "globs:\n"
        "alwaysApply: false\n"
        "---\n"
    ),
    ".openclaw/commands/t3-fleet.md": (
        "---\n"
        "name: t3-fleet\n"
        f"description: {DESCRIPTION}\n"
        "---\n"
    ),
}


def _strip_frontmatter(text: str) -> str:
    if not text.startswith("---\n"):
        return text
    return text.split("\n---\n", 1)[1].lstrip("\n")


def _section(text: str, heading: str) -> str:
    """Return one `## heading` section, up to the next heading of any level."""
    start = text.index(f"\n## {heading}\n") + 1
    rest = text[start:]
    end = rest.find("\n## ", 1)
    return (rest if end == -1 else rest[:end]).rstrip() + "\n"


def render() -> dict[str, str]:
    skill_body = _strip_frontmatter(SKILL.read_text(encoding="utf-8")).rstrip()
    tool_text = TOOL.read_text(encoding="utf-8")
    runtime_policy = _section(tool_text, "Runtime mode policy")
    approvals = _section(tool_text, "Approval and effects")
    projection = "\n\n".join(
        (
            skill_body,
            approvals.rstrip(),
            runtime_policy.rstrip(),
            "The Brigade catalog entry stays at `approval_mode = \"always\"`. See\n"
            "`tools/t3-fleet-dispatch.md` for the full tool projection and\n"
            "`skills/t3-fleet-dispatch/references/contract.md` for the request contract.",
        )
    )
    return {
        path: f"{header}\n{BANNER}\n\n{projection}\n"
        for path, header in TARGETS.items()
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)

    stale: list[str] = []
    for relative, content in render().items():
        destination = ROOT / relative
        current = (
            destination.read_text(encoding="utf-8") if destination.exists() else None
        )
        if current == content:
            continue
        if args.check:
            stale.append(relative)
            continue
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")
        print(f"wrote {relative}")
    if stale:
        print("stale projections: " + ", ".join(sorted(stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
