"""The Brigade policy `sources` wire contract, tested against real root output.

`tests/fixtures/brigade-policy-resolve.json` is generated by
`scripts/generate-policy-wire-fixture.py` from Brigade's own resolver, so these
tests check the T3 parser against what the root actually emits rather than
against an envelope this repo invented.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
import unittest
from pathlib import Path

from t3_fleet.errors import ValidationError
from t3_fleet.policy import normalize_policy_envelope

ROOT = Path(__file__).resolve().parents[1]
FIXTURE_PATH = ROOT / "tests" / "fixtures" / "brigade-policy-resolve.json"
GENERATOR = ROOT / "scripts" / "generate-policy-wire-fixture.py"

# The Brigade source tree is named explicitly, never discovered from PATH: an
# installed `brigade` that happens to be on PATH is not evidence about the
# source tree this fixture claims to come from.
BRIGADE_SOURCE = os.environ.get("T3_FLEET_BRIGADE_SOURCE")

FIXTURE = json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))
CASES = {case["case"]: case for case in FIXTURE["cases"]}


def envelope(case: str) -> dict:
    return json.loads(json.dumps(CASES[case]["envelope"]))


class FixtureProvenanceTests(unittest.TestCase):
    def test_fixture_records_the_exact_root_files_it_came_from(self) -> None:
        provenance = FIXTURE["provenance"]
        files = provenance["brigade_source_files"]
        self.assertIn("src/brigade/fleet_policy.py", files)
        self.assertIn("src/brigade/fleet_hub_policy_api.py", files)
        for digest in files.values():
            self.assertRegex(digest, r"^sha256:[0-9a-f]{64}$")
        self.assertEqual(
            provenance["generator"], "scripts/generate-policy-wire-fixture.py"
        )

    def test_public_resolve_envelope_is_still_six_keys(self) -> None:
        self.assertEqual(
            FIXTURE["public_envelope_keys"],
            ["schema", "version", "digest", "effective", "sources", "ack_required"],
        )
        for case in FIXTURE["cases"]:
            self.assertEqual(
                sorted(case["envelope"]),
                sorted(FIXTURE["public_envelope_keys"]),
            )


class RealWireEnvelopeTests(unittest.TestCase):
    """The parser accepts real Hub output and keeps every resolved value."""

    def test_inheritance_case_parses_and_keeps_the_winning_layer(self) -> None:
        parsed = normalize_policy_envelope(envelope("inheritance"))
        sources = parsed["sources"]
        # A consumer-layer win and a repository-layer win both survive parsing.
        self.assertEqual(sources["roles.review"]["layer"], "consumer:t3-fleet")
        self.assertEqual(sources["roles.review"]["value"], "example-review-seat")
        self.assertEqual(
            sources["execution.machine"]["layer"],
            "repo:github.com/example-org/example-public-repo",
        )
        self.assertEqual(sources["execution.machine"]["value"], "example-machine")
        self.assertEqual(sources["execution.concurrency"]["value"], 2)
        self.assertIs(sources["data.allow_training"]["value"], False)

    def test_unset_leaf_keeps_a_null_layer_and_a_null_value(self) -> None:
        # Brigade emits every path it saw, including ones no layer ever set.
        # Requiring a non-empty layer string here would reject real Hub output.
        source = normalize_policy_envelope(envelope("inheritance"))["sources"][
            "execution.timeout_seconds"
        ]
        self.assertIsNone(source["layer"])
        self.assertIsNone(source["value"])
        self.assertEqual([step["action"] for step in source["chain"]][0], "inherit")

    def test_explicit_override_wins_at_the_session_layer(self) -> None:
        sources = normalize_policy_envelope(envelope("explicit_override"))["sources"]
        self.assertEqual(sources["roles.impl"]["layer"], "session")
        self.assertEqual(sources["roles.impl"]["value"], "example-override-seat")
        self.assertEqual(sources["execution.machine"]["value"], "example-other-machine")

    def test_a_session_null_inherits_instead_of_clearing(self) -> None:
        source = normalize_policy_envelope(envelope("explicit_override"))["sources"][
            "roles.review"
        ]
        self.assertEqual(source["layer"], "consumer:t3-fleet")
        self.assertEqual(source["value"], "example-review-seat")
        self.assertEqual(source["chain"][-1], {"layer": "session", "action": "inherit", "value": None})

    def test_privacy_constraint_keeps_the_denied_override_visible(self) -> None:
        """The winning value differs from the last chain step, so it must be carried.

        This is the case that a layer-and-chain-only parser silently gets wrong:
        the chain still shows the session asking for training, while the value
        the fleet is actually governed by is the constrained `False`.
        """
        source = normalize_policy_envelope(envelope("privacy_constraint"))["sources"][
            "data.allow_training"
        ]
        self.assertEqual(source["layer"], "constraint:repo-privacy-training")
        self.assertIs(source["value"], False)
        self.assertEqual(
            source["chain"][-1],
            {"layer": "session", "action": "set", "value": True},
        )

    def test_every_fixture_case_round_trips_its_sources(self) -> None:
        for name, case in CASES.items():
            with self.subTest(case=name):
                parsed = normalize_policy_envelope(envelope(name))
                self.assertEqual(parsed["sources"], case["envelope"]["sources"])


class WireStrictnessTests(unittest.TestCase):
    """Accepting `value` must not loosen anything else."""

    def test_an_unknown_source_field_is_still_rejected(self) -> None:
        payload = envelope("inheritance")
        payload["sources"]["roles.impl"]["origin"] = "example"
        with self.assertRaises(ValidationError):
            normalize_policy_envelope(payload)

    def test_an_unknown_chain_field_is_still_rejected(self) -> None:
        payload = envelope("inheritance")
        payload["sources"]["roles.impl"]["chain"][0]["note"] = "example"
        with self.assertRaises(ValidationError):
            normalize_policy_envelope(payload)

    def test_a_missing_value_field_is_rejected(self) -> None:
        payload = envelope("inheritance")
        del payload["sources"]["roles.impl"]["value"]
        with self.assertRaises(ValidationError):
            normalize_policy_envelope(payload)

    def test_a_missing_layer_field_is_rejected(self) -> None:
        payload = envelope("inheritance")
        del payload["sources"]["roles.impl"]["layer"]
        with self.assertRaises(ValidationError):
            normalize_policy_envelope(payload)

    def test_an_unbounded_source_value_is_rejected(self) -> None:
        payload = envelope("inheritance")
        payload["sources"]["roles.impl"]["value"] = {"nested": "object"}
        with self.assertRaises(ValidationError):
            normalize_policy_envelope(payload)

    def test_an_oversize_source_value_is_rejected(self) -> None:
        payload = envelope("inheritance")
        payload["sources"]["roles.impl"]["value"] = "x" * 513
        with self.assertRaises(ValidationError):
            normalize_policy_envelope(payload)


@unittest.skipUnless(
    BRIGADE_SOURCE,
    "cross-repo interoperability check: set T3_FLEET_BRIGADE_SOURCE to a Brigade "
    "source tree to run it (an installed `brigade` on PATH is deliberately not used)",
)
class BrigadeInteroperabilityTests(unittest.TestCase):
    """Regenerate the fixture from a named Brigade tree and diff it.

    This is the only check that can catch the root moving the `sources` shape
    again. It is skipped, visibly, when no Brigade source tree is named, and it
    never falls back to whatever `brigade` is installed on PATH.
    """

    def test_wire_contract_matches_the_named_brigade_source(self) -> None:
        source = Path(BRIGADE_SOURCE).expanduser()
        self.assertTrue(
            (source / "src" / "brigade" / "fleet_policy.py").is_file(),
            f"T3_FLEET_BRIGADE_SOURCE is not a Brigade source tree: {source}",
        )
        completed = subprocess.run(
            [
                sys.executable,
                str(GENERATOR),
                "--brigade-source",
                str(source),
                "--check-contract",
            ],
            capture_output=True,
            text=True,
            timeout=120,
            check=False,
        )
        self.assertEqual(
            completed.returncode,
            0,
            f"the Brigade wire contract moved against {source}.\n"
            f"{completed.stdout}\n{completed.stderr}",
        )


if __name__ == "__main__":
    unittest.main()
